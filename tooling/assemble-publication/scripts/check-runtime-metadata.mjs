import assert from 'node:assert/strict';
import path from 'node:path';
import { decodeMemoMetadata, readContainedFile, validateMemoTree } from '../dist/src/plugins/memos.js';
import { walkSafeTree } from '../dist/src/index.js';
const root = path.resolve(import.meta.dirname, '../../..');
const publication = JSON.parse(new TextDecoder('utf-8', { fatal: true }).decode(readContainedFile('artifacts/publication.json', root, 'runtime publication metadata', 4 * 1024 * 1024)));
const legacy = decodeMemoMetadata(publication.memos);
assert.equal(legacy.enabled, false, 'blog manifest preserves legacy floor only');
const releaseFiles = (await walkSafeTree(path.join(root, 'dist'))).files;
assert.deepEqual([...publication.inventory].sort(), [...releaseFiles].sort());
await validateMemoTree(path.join(root, 'dist'), releaseFiles);
await validateMemoTree(path.join(root, 'artifacts/site'), (await walkSafeTree(path.join(root, 'artifacts/site'))).files);
process.stdout.write('[package-runtime] blog inventory and retained legacy Memo floor passed\n');
